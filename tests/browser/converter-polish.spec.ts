async function activate(page:Page,control:Locator){
  if(test.info().project.use.hasTouch)await control.tap();else await control.click();
}
async function choose(page:Page,label:string,option:string){
  await activate(page,page.getByRole('combobox',{name:label,exact:true}));
  await activate(page,page.getByRole('option',{name:option,exact:true}));
}
async function process(page:Page,raw:string){
  if(!await page.getByRole('textbox',{name:'Nutrition response',exact:true}).isVisible())await page.locator('[data-convert-source-panel]>summary').click();
  await page.getByRole('textbox',{name:'Nutrition response',exact:true}).fill(raw);
  await activate(page,page.getByRole('button',{name:'Process table',exact:true}));
  await expect(page.locator('[data-convert-table] input')).not.toHaveCount(0);
}
async function standalone(page:Page,target:'master'|'ingredients'='master',raw=plain){
  await choose(page,'Conversion mode','New table');
  await process(page,raw);
  await choose(page,'New table destination',target==='master'?'Master - Synthetic Master':'Ingredients');
  if(target==='master')await page.getByLabel('Master date',{exact:true}).fill('2023-03-16');
  else{await choose(page,'Row 1 Type','Homemade');await choose(page,'Row 2 Type','Packaged');}
}
async function trackedResponse(page:Page,zero=false){
  return page.evaluate(zero=>{
    const batch=window.converterPolish.read().book.foodCapture!.builder!;
    return`Batch ID: ${batch.id}\nItem ID,Dish Name,Calories,Protein,Fat,Carbs,Sugar,Sodium,Grams,Amount,Unit\n`+batch.items.filter(item=>item.selected).map(item=>`${item.id},${item.kind==='ingredient'?'Synthetic mochi':item.name.replaceAll(',','')},${zero?'0,0,0,0,0,0':'70,1,2,12,0,10'},${item.kind==='ingredient'?'25,1,each':',,'}`).join('\n');
  },zero);
}
